"""Write the AI notes next to each video's note (inside the video's folder)."""

import json
import os
import sqlite3
from datetime import datetime
from typing import Optional
from urllib.parse import quote

from config import KINDS
from pipeline.selection import ai_note_path

TITLES = {"knowledge": "AI knowledge", "visual": "AI visual description"}


def render_note(row: sqlite3.Row, detail: sqlite3.Row, category: Optional[str] = None) -> str:
    front = {
        "video_id": row["video_id"],
        "title": detail["title"],
        "ai_kind": row["kind"],
        "model": row["model"],
        "mode": row["mode"],
        "media_resolution": row["media_resolution"],
        "prompt_version": row["prompt_hash"],
        "generated_at": row["completed_at"],
        "finish_reason": row["finish_reason"],
        "prompt_tokens": row["prompt_tokens"],
        "cached_tokens": row["cached_tokens"],
        "output_tokens": row["output_tokens"],
        "thinking_tokens": row["thinking_tokens"],
        "category": category,
        "paraphrased": bool(row["paraphrased"]),
    }
    lines = ["---"] + [f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in front.items()] + ["---", ""]
    links = f"[Video note]({quote(detail['note_file'])}) · [YouTube](https://www.youtube.com/watch?v={row['video_id']})"
    lines += [f"> {TITLES[row['kind']]} generated by {row['model']}. {links}", ""]
    if row["paraphrased"]:
        lines += ["> **Note:** Gemini blocked a word-for-word copy of this video's code or text, so they are "
                  "summarised in its own words here.", ""]
    if row["finish_reason"] == "MAX_TOKENS":
        lines += ["> **Note:** the answer reached the model's maximum output length, so the end may be cut off.", ""]
    return "\n".join(lines) + "\n" + row["output_text"].rstrip() + "\n"


def write_note(conn: sqlite3.Connection, notes_dir: str, video_id: str, kind: str, force: bool) -> Optional[str]:
    """Write one finished AI note; returns its path relative to notes_dir, or None if its folder is gone.

    An existing file is never overwritten: with --force the old one is renamed to "... (old <time>).md".
    """
    row = conn.execute("SELECT * FROM ai_note WHERE video_id = ? AND kind = ?", (video_id, kind)).fetchone()
    detail = conn.execute("SELECT * FROM video_detail WHERE video_id = ?", (video_id,)).fetchone()
    if row is None or detail is None or not detail["note_path"]:
        return None
    if not os.path.exists(os.path.join(notes_dir, detail["note_path"])):
        return None
    path = ai_note_path(notes_dir, detail["note_path"], detail["note_file"], kind)
    if os.path.exists(path):
        if not force:
            return os.path.relpath(path, notes_dir)
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        os.replace(path, f"{path[: -len('.md')]} (old {stamp}).md")
    with open(path, "w", encoding="utf-8") as fh:
        classified = conn.execute(
            "SELECT category FROM ai_classification WHERE video_id = ? AND status = 'done'", (video_id,)
        ).fetchone()
        fh.write(render_note(row, detail, classified["category"] if classified else None))
    return os.path.relpath(path, notes_dir).replace(os.sep, "/")


def suffix_of(kind: str) -> str:
    return KINDS[kind][1]
